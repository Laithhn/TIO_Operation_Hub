using System.Globalization;
using System.Linq.Expressions;
using System.Text;
using Microsoft.EntityFrameworkCore;

namespace TioHub.Api.Common;

public sealed record Paged<T>(IReadOnlyList<T> Items, int Page, int PageSize, int TotalCount);

public sealed record PageQuery(int Page, int PageSize)
{
    public static PageQuery From(int? page, int? pageSize) => new(Math.Max(1, page ?? 1), Math.Clamp(pageSize ?? 15, 1, 200));
}

public static class PagingExtensions
{
    public static async Task<Paged<T>> ToPagedAsync<T>(this IQueryable<T> query, PageQuery p, CancellationToken ct)
    {
        var total = await query.CountAsync(ct);
        var items = await query.Skip((p.Page - 1) * p.PageSize).Take(p.PageSize).ToListAsync(ct);
        return new Paged<T>(items, p.Page, p.PageSize, total);
    }

    /// <summary>Applies a whitelisted sort ("name" or "-name"), falling back to the default key (UX-03 sorting).</summary>
    public static IQueryable<T> SortBy<T>(this IQueryable<T> q, string? sort, IReadOnlyDictionary<string, Expression<Func<T, object?>>> keys, string fallback)
    {
        var s = string.IsNullOrWhiteSpace(sort) ? fallback : sort.Trim();
        var desc = s.StartsWith('-');
        var name = desc ? s[1..] : s;
        if (!keys.TryGetValue(name, out var key)) { key = keys[fallback.TrimStart('-')]; desc = fallback.StartsWith('-'); }
        return desc ? q.OrderByDescending(key) : q.OrderBy(key);
    }
}

/// <summary>Row versions travel as ETags; updates must send If-Match (NFR-04).</summary>
public static class Concurrency
{
    public static string Version(byte[] rowVersion) => Convert.ToBase64String(rowVersion);

    public static IResult WithETag(this HttpContext ctx, Entity entity, object body)
    {
        ctx.Response.Headers.ETag = $"\"{Version(entity.RowVersion)}\"";
        return Results.Ok(body);
    }

    /// <summary>Reads If-Match and makes EF compare it with the stored row version on save.</summary>
    public static void ExpectVersion(this DbContext db, HttpContext ctx, Entity entity)
    {
        var header = ctx.Request.Headers.IfMatch.FirstOrDefault();
        if (string.IsNullOrWhiteSpace(header)) throw new PreconditionRequiredException();
        var raw = header.Trim();
        if (raw.StartsWith("W/", StringComparison.Ordinal)) raw = raw[2..];
        raw = raw.Trim('"');
        byte[] bytes;
        try { bytes = Convert.FromBase64String(raw); }
        catch (FormatException) { throw new PreconditionRequiredException(); }
        if (!bytes.AsSpan().SequenceEqual(entity.RowVersion))
            throw new DbUpdateConcurrencyException("Stale version");
        db.Entry(entity).Property(e => e.RowVersion).OriginalValue = bytes;
    }
}

/// <summary>Column for a CSV export: header, definition shown in the export header block, and the value.</summary>
public sealed record CsvColumn<T>(string Header, string Definition, Func<T, object?> Value);

/// <summary>
/// CSV export (DAS-09, Section 7): header block with report, generation time, selected time zone, user and filters, then column
/// definitions, then rows. Every cell is protected against spreadsheet formula interpretation.
/// </summary>
public static class Csv
{
    public static byte[] Build<T>(string report, string user, string filters, TimeZoneInfo zone, DateTimeOffset generatedAt,
        IReadOnlyList<CsvColumn<T>> columns, IEnumerable<T> rows, IEnumerable<(string Label, string Value)>? summary = null)
    {
        var sb = new StringBuilder();
        sb.Append('﻿');
        sb.AppendLine(Line(["TIO Operations Hub export", report]));
        sb.AppendLine(Line(["Generated", Format(generatedAt, zone)]));
        sb.AppendLine(Line(["Time zone", zone.Id]));
        sb.AppendLine(Line(["Generated by", user]));
        sb.AppendLine(Line(["Filters", string.IsNullOrWhiteSpace(filters) ? "none" : filters]));
        foreach (var (label, value) in summary ?? []) sb.AppendLine(Line(["Summary: " + label, value]));
        foreach (var c in columns) sb.AppendLine(Line(["Column: " + c.Header, c.Definition]));
        sb.AppendLine();
        sb.AppendLine(Line(columns.Select(c => (object?)c.Header)));
        foreach (var r in rows) sb.AppendLine(Line(columns.Select(c => Normalize(c.Value(r), zone))));
        return Encoding.UTF8.GetBytes(sb.ToString());
    }

    public static string FileName(string report, DateTimeOffset now) =>
        $"tio-hub-{report.ToLowerInvariant().Replace(' ', '-')}-{now.UtcDateTime:yyyyMMdd-HHmm}.csv";

    private static object? Normalize(object? v, TimeZoneInfo zone) => v is DateTimeOffset d ? Format(d, zone) : v;

    /// <summary>A62: a cell value as shown in previews and spreadsheets — times in the chosen zone, enums by name, numbers kept numeric.</summary>
    public static object? Display(object? v, TimeZoneInfo zone) => v switch
    {
        null => null,
        DateTimeOffset d => Format(d, zone),
        DateOnly d => d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
        Enum e => e.ToString(),
        bool or int or long or decimal or double => v,
        _ => Convert.ToString(v, CultureInfo.InvariantCulture)
    };

    public static string Format(DateTimeOffset d, TimeZoneInfo zone) =>
        TimeZoneInfo.ConvertTime(d, zone).ToString("yyyy-MM-dd HH:mm zzz", CultureInfo.InvariantCulture);

    private static string Line(IEnumerable<object?> cells) => string.Join(",", cells.Select(Cell));

    public static string Cell(object? value)
    {
        var s = value switch
        {
            null => "",
            DateOnly d => d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
            decimal m => m.ToString(CultureInfo.InvariantCulture),
            double m => m.ToString(CultureInfo.InvariantCulture),
            bool b => b ? "Yes" : "No",
            _ => Convert.ToString(value, CultureInfo.InvariantCulture) ?? ""
        };
        // Formula injection: a leading =, +, -, @, tab or CR makes spreadsheets evaluate the cell.
        if (s.Length > 0 && "=+-@\t\r".Contains(s[0]) && value is not (decimal or double or int or long)) s = "'" + s;
        return s.IndexOfAny([',', '"', '\n', '\r']) >= 0 ? "\"" + s.Replace("\"", "\"\"") + "\"" : s;
    }
}

public static class Text
{
    public static string? Clean(string? s) => string.IsNullOrWhiteSpace(s) ? null : s.Trim();

    /// <summary>Normalized name for uniqueness checks: trimmed, single spaces, upper case.</summary>
    public static string Norm(string? s) => string.Join(' ', (s ?? "").Trim().Split(' ', StringSplitOptions.RemoveEmptyEntries)).ToUpperInvariant();

    /// <summary>Sortable key for a version string, so 4.10.0 sorts after 4.9.2. Only compared within one product (Section 6.3).</summary>
    public static string VersionKey(string version)
    {
        var parts = version.Trim().Split(['.', '-', '_', ' '], StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder();
        foreach (var p in parts.Take(6))
        {
            if (sb.Length > 0) sb.Append('.');
            sb.Append(int.TryParse(p, out var n) ? n.ToString("D6", CultureInfo.InvariantCulture) : p.ToLowerInvariant());
        }
        var key = sb.ToString();
        return key.Length > 100 ? key[..100] : key;
    }
}
