using System.Text;
using System.Text.Json;
using TioHub.Api.Security;

// Source generation only: no host, database connection, seeding or migrations are executed.
var root = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../../"));
var rights = RightsCatalog.All;

// The browser mirrors prerequisites for display. Refer to keys by index so the initial JavaScript does not repeat them.
var index = rights.Select((r, i) => (r.Key, i)).ToDictionary(x => x.Key, x => x.i);
File.WriteAllText(Path.Combine(root, "src/web/src/rightsRequirements.json"), JsonSerializer.Serialize(new
{
    keys = rights.Select(r => r.Key).ToArray(),
    requires = rights.Select(r => r.Requires.Select(k => index[k]).ToArray()).ToArray()
}) + "\n");
File.WriteAllText(Path.Combine(root, "src/web/src/rightsCatalog.json"), "[\n" + string.Join(",\n", rights.Select(r => "  " + JsonSerializer.Serialize(new
{
    key = r.Key, label = r.Label, description = r.Description, module = r.Module, feature = r.Feature, featureLabel = r.FeatureLabel,
    action = r.Action, kind = r.Kind, riskLevel = r.RiskLevel, supportsScope = r.SupportsScope, requires = r.Requires, displayOrder = r.DisplayOrder, isActive = true
}))) + "\n]\n");

// The matrix of record: every right, then every API operation. Generated, so it cannot drift from the code.
var sb = new StringBuilder();
sb.AppendLine("# Rights coverage matrix").AppendLine();
sb.AppendLine("Generated by `dotnet run --project build/RightsManifest` from `Security/RightsCatalog.cs` and `Security/EndpointRights.cs`. Do not edit. `EndpointRightsCoverageTests` fails if an API route has no entry, and `Rights_matrix_is_current` fails if this file is stale.").AppendLine();
sb.AppendLine("Screens, menus, tabs and controls are in [RIGHTS-UI-COVERAGE.md](RIGHTS-UI-COVERAGE.md).").AppendLine();
var table = EndpointRights.Table;
sb.AppendLine($"**{rights.Length} rights. {table.Count} API operations:** "
    + string.Join(", ", table.Values.GroupBy(p => p.Decision).OrderBy(g => g.Key).Select(g => $"{g.Count()} {g.Key}")) + ".").AppendLine();
sb.AppendLine("How to read an operation's decision:").AppendLine();
sb.AppendLine("- **Public:** needs no sign-in, for the reason shown.");
sb.AppendLine("- **Authenticated:** any signed-in account with access. It returns only the caller's own data or data filtered by right, for the reason shown.");
sb.AppendLine("- **Rights:** the listed rights are checked before the handler runs.");
sb.AppendLine("- **Handler:** the rights depend on the record (data scope, limited exceptions, workflow), so the handler checks them.");
sb.AppendLine("- **Dynamic:** the requirement depends on the record type or a query value, and the filter works it out on each request.").AppendLine();
sb.AppendLine("Each right's prerequisites apply too. All record operations also enforce data scope: client, project or team. A record outside scope answers 404.").AppendLine();
sb.AppendLine("## Rights catalog").AppendLine();
foreach (var module in rights.GroupBy(r => r.Module))
{
    sb.AppendLine($"### {module.Key}").AppendLine();
    sb.AppendLine("| Right | Feature | Label | Kind | Risk | Requires |").AppendLine("|---|---|---|---|---|---|");
    foreach (var r in module)
        sb.AppendLine($"| `{r.Key}` | {r.FeatureLabel} | {Cell(r.Label)} | {r.Kind} | {r.RiskLevel} | {(r.Requires.Length == 0 ? "None" : string.Join(", ", r.Requires.Select(k => $"`{k}`")))} |");
    sb.AppendLine();
}
sb.AppendLine("## API operations").AppendLine();
sb.AppendLine("| Operation | Decision | Checked before the handler | Checked in the handler | Note |").AppendLine("|---|---|---|---|---|");
foreach (var (key, policy) in table.OrderBy(x => x.Key.Split(' ', 2)[1], StringComparer.Ordinal).ThenBy(x => x.Key, StringComparer.Ordinal))
    sb.AppendLine($"| `{key.Replace("|", "\\|")}` | {policy.Decision}{(policy.Dynamic == DynamicPolicy.None ? "" : $": {policy.Dynamic}")} | {Keys(policy.Rights)} | {Keys(policy.HandlerRights)} | {Cell(policy.Remark ?? "")} |");
File.WriteAllText(Path.Combine(root, "docs/RIGHTS-COVERAGE-MATRIX.md"), sb.ToString());

if (args.Length > 0)
    File.WriteAllText(args[0], JsonSerializer.Serialize(rights));
Console.WriteLine($"Generated {rights.Length} rights and {table.Count} API operations.");

static string Keys(string[] keys) => keys.Length == 0 ? "" : string.Join(", ", keys.Select(k => $"`{k}`"));
static string Cell(string text) => text.Replace("|", "\\|");
