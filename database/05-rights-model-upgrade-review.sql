SELECT u.AccountName, d.NewKey, d.ExpiresAt FROM #NewDeny d JOIN [iam].[User] u ON u.Id = d.UserId ORDER BY u.AccountName, d.NewKey;

PRINT '5. Role grants carried only because every holder composed them (rule 2). Future holders get these too';
SELECT r.Name AS RoleName, n.NewKey FROM #RoleNew n JOIN [iam].[AppRole] r ON r.Id = n.RoleId WHERE n.[Rule] = 2 ORDER BY r.Name, n.NewKey;

PRINT '6. Stored action grants that are not carried: they could not be used under the old rules';
SELECT r.Name AS RoleName, o.OldKey FROM #RoleOld o JOIN [iam].[AppRole] r ON r.Id = o.RoleId
WHERE EXISTS (SELECT 1 FROM #Map m WHERE m.NewKey = o.OldKey) AND NOT EXISTS (SELECT 1 FROM #RoleNew n WHERE n.RoleId = o.RoleId AND n.NewKey = o.OldKey)
ORDER BY r.Name, o.OldKey;

